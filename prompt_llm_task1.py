anthropic_client = Anthropic(
    api_key=os.environ.get("ANTHROPIC_API_KEY"),
)

gemini_client = genai.Client()

# prompt base that will be injected with the abstract (may need some tweaking)
prompt_base = (
    "Acting as an academic expert, generate one one-sentence scientific "
    "question that scholars might ask about a piece of scientific literature, "
    "based on a specific abstract from a scientific paper, which is provided after the keyword 'Abstract:'. The question should "
    "require the synthesis of multiple scientific papers to answer (a "
    "literature-review style question). Abstract:"
)

# 1a. Load current JSON, if it exists. Build off of this.
# (Safeguard for if it crashes in the middle, can pick up where it left off)
def load_file(filename):
    if os.path.exists(filename):
        with open(filename, "r") as f:
            return json.load(f)
    return []


# 1b. Parse the abstracts JSON for an abstract; cross-check ids of abstract
# JSON and current JSON being build to ensure that an abstract
# has not been prompted with yet (checks using OpenAlex id, given in json formatting for abstracts)
def completed_abstract_ids(filename):
    content = load_file(filename)
    return [entry["id"] for entry in content]

# Inject the abstract into the prompt base.
def build_prompt(abstract):
    return f"{prompt_base} {abstract}"

# Calls a given LLM and returns the generated question. If llm is "testing", returns a placeholder question.
def prompt_llm(prompt, llm):
    if llm == "openai":
        response = openai_client.chat.completions.create(
            model="gpt-5.5",
            messages=[{"role": "user", "content": prompt}],
        )
        return response.choices[0].message.content

    # RIP LLama.
    # elif llm == "llama":
        # response = llama_client.chat.completions.create(
        #     messages=[{"content": prompt, "role": "user"}],
        #     model="model",  # TODO: set real model name
        # )
        # return response["completion_message"]["content"]["text"]

    elif llm == "anthropic":
        response = anthropic_client.messages.create(
            max_tokens=1024,
            messages=[{"role": "user", "content": prompt}],
            model="claude-opus-4-8",
        )
        return response.content[0].text

    elif llm == "gemini":
        client = gemini_client
        response = client.interactions.create(
            model="gemini-3.5-flash",
            input=prompt
        )
        return response.output_text

    else:  # testing mode
        return "This is a test question and is not generated by an LLM. It is a placeholder for testing purposes."

# Append a new {id, model, question} entry to the output JSON file.
def build_json(filename, abstract_id, llm, question):
    output_file = load_file(filename)

    new_entry = {
        "id": abstract_id,
        "model": llm,
        "question": question.strip(),
    }

    output_file.append(new_entry)
    with open(filename, "w") as f:
        json.dump(output_file, f, indent=2)


def generate_questions(abstracts_file, output_file, llm="testing"):
    """
    Reads abstracts from abstracts_file, prompts the given llm for a
    literature-review-style question on each one, and appends results
    to output_file (skipping abstracts already present in output_file).
    """
    abstracts = load_file(abstracts_file)
    completed_abstracts = completed_abstract_ids(output_file)

    for abstract in abstracts:
        abstract_id = abstract["id"]
        if abstract_id in completed_abstracts:
            continue

        prompt = build_prompt(abstract["abstract"])
        question = prompt_llm(prompt, llm)
        build_json(output_file, abstract_id, llm, question)

    print(f"Done. Questions saved to {output_file}")


